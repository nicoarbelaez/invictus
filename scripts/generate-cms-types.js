function main() {
  try {
    const types = parseContentTypes()
    const output = generateTypeScript(types)
    fs.writeFileSync(OUTPUT_PATH, output, 'utf-8')
    console.log(`✓ Generated ${OUTPUT_PATH}`)
  } catch (e) {
    console.error('Error:', e.message)
    process.exit(1)
  }
}

main()
