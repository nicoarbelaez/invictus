#!/usr/bin/env node
const fs = require('fs')
const path = require('path')

const CMS_TYPES_PATH = path.join(__dirname, '../apps/cms/types/generated/contentTypes.d.ts')
const OUTPUT_PATH = path.join(__dirname, '../apps/ecommerce/src/lib/cms/strapi.generated.ts')

function parseContentTypes() {
  const content = fs.readFileSync(CMS_TYPES_PATH, 'utf-8')
  const types = new Map()

  const interfaceRegex =
    /export interface (Api\w+?\w+?) extends Struct\.(CollectionTypeSchema|SingleTypeSchema)/g
  let match

  while ((match = interfaceRegex.exec(content)) !== null) {
    const interfaceName = match[1]
    const typeKind = match[2]
    const interfaceStart = match.index

    const apiNameMatch = interfaceName.match(/Api(\w+?)\1/)
    const apiName = apiNameMatch
      ? apiNameMatch[1].toLowerCase()
      : interfaceName.replace(/^Api/, '').toLowerCase()

    const attrStart = content.indexOf('attributes: {', interfaceStart)
    if (attrStart === -1) continue

    const attrEnd = content.indexOf('\n  }', attrStart)
    const attrBlock = content.slice(attrStart, attrEnd)

    const attrs = []
    const skipFields = new Set([
      'createdAt',
      'updatedAt',
      'publishedAt',
      'createdBy',
      'updatedBy',
      'locale',
      'localizations',
    ])

    const lines = attrBlock.split('\n').filter((l) => l.trim())
    for (let i = 0; i < lines.length; i++) {
      const line = lines[i].trim()
      if (!line.includes(':')) continue

      const nameMatch = line.match(/^(\w+):/)
      if (!nameMatch) continue

      const name = nameMatch[1]
      if (skipFields.has(name)) continue

      let fullType = line
      let nextIdx = i + 1
      while (
        nextIdx < lines.length &&
        !lines[nextIdx].trim().match(/^\w+:/) &&
        !lines[nextIdx].trim().endsWith('}')
      ) {
        fullType += ' ' + lines[nextIdx].trim()
        nextIdx++
      }

      let mappedType = mapAttributeType(name, fullType)
      if (mappedType) {
        attrs.push({ name, type: mappedType })
      }
    }

    const isPublished = typeKind === 'CollectionTypeSchema'
    types.set(apiName, { name: apiName, apiName, attrs, isPublished })
  }

  return types
}

function mapAttributeType(name, fullType) {
  if (fullType.includes('Schema.Attribute.Relation')) {
    const match = fullType.match(/'(\w+)'.*?'api::(\w+)\.(\w+)'/)
    if (match) {
      const [, kind, , singular] = match
      const entityName = singular.charAt(0).toUpperCase() + singular.slice(1)
      return kind === 'oneToMany' ? `${entityName}[] | null` : `${entityName} | null`
    }
  }

  if (fullType.includes('Schema.Attribute.Component')) {
    const match = fullType.match(/'(\w+)\.(\w+)'[^>]*,\s*(true|false)/)
    if (match) {
      const [, namespace, compName, repeatable] = match
      const parts = `${namespace}-${compName}`
        .split('-')
        .map((p) => p.charAt(0).toUpperCase() + p.slice(1))
      const componentName = parts.join('')
      return repeatable === 'true' ? `${componentName}[] | null` : `${componentName} | null`
    }
  }

  if (fullType.includes('Schema.Attribute.Media')) {
    const repeatable = fullType.includes('true')
    return repeatable ? 'StrapiMedia[] | null' : 'StrapiMedia | null'
  }

  const typeMap = {
    'Schema.Attribute.Text': 'string',
    'Schema.Attribute.String': 'string',
    'Schema.Attribute.RichText': 'string',
    'Schema.Attribute.Email': 'string',
    'Schema.Attribute.Password': 'string',
    'Schema.Attribute.UID': 'string',
    'Schema.Attribute.Integer': 'number',
    'Schema.Attribute.Float': 'number',
    'Schema.Attribute.BigInteger': 'string',
    'Schema.Attribute.Decimal': 'string',
    'Schema.Attribute.Boolean': 'boolean',
    'Schema.Attribute.DateTime': 'string',
    'Schema.Attribute.Date': 'string',
    'Schema.Attribute.Time': 'string',
    'Schema.Attribute.JSON': 'unknown',
    'Schema.Attribute.Blocks': 'unknown',
    'Schema.Attribute.Enumeration': 'string',
  }

  for (const [key, val] of Object.entries(typeMap)) {
    if (fullType.includes(key)) return `${val} | null`
  }

  return null
}

